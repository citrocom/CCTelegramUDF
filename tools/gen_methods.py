"""
Generates CCTelegramUDF_Methods.au3 from the machine-readable Telegram Bot API specification.

Specification source (MIT): https://github.com/PaulSonOfLars/telegram-bot-api-spec  (file api.json)

Usage:
    git clone --depth 1 https://github.com/PaulSonOfLars/telegram-bot-api-spec spec
    python gen_methods.py spec/api.json ../CCTelegramUDF_Methods.au3

Rules for the generated AutoIt functions
    - name: _CCTelegram_ + method name with a capital first letter (sendMessage -> _CCTelegram_SendMessage)
    - positional parameters, in the order of the documentation: every required parameter, plus chat_id (if the
      method has one) and message_id (if the method has chat_id AND message_id)
    - last parameter $vOpt = Default: all other parameters as Dictionary (_CCTelegram_Obj) or JSON string
    - optional positional parameters (e.g. chat_id of editMessageText) accept Default
"""
import json
import sys
import textwrap

PRIMITIVE = {"String", "Integer", "Boolean", "Float"}
RESERVED_HELPERS = {
    "Init", "GetToken", "Version", "SetProxy", "SetTimeouts", "SetRetry", "SetDebug", "LastErrorCode",
    "LastErrorDescription", "LastRetryAfter", "LastMigrateToChatId", "LastHttpStatus", "LastResponse", "Call", "Obj",
    "Arr", "File", "InputMedia", "Get", "UpdateType", "Poll", "GetOffset", "SetOffset", "DownloadFile", "InlineButton",
    "UrlButton", "InlineKeyboard", "ReplyKeyboard", "ReplyKeyboardRemove", "ForceReply", "EscapeMarkdownV2",
    "EscapeHtml", "UrlEncode", "UrlDecode", "JsonDecode", "JsonEncode",
}


def kind(types):
    if any(t == "InputFile" for t in types):
        return "file"
    if all(t in PRIMITIVE for t in types):
        return "prim"
    return "json"


def prefix(types):
    k = kind(types)
    if k == "file":
        return "v"
    if k == "json":
        return "a" if all(t.startswith("Array of") for t in types) else "o"
    if len(types) > 1:
        return "v"
    return {"String": "s", "Integer": "i", "Boolean": "b", "Float": "f"}[types[0]]


def camel(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def type_text(types):
    return " or ".join(types)


def main(spec_path, out_path):
    with open(spec_path, encoding="utf-8") as fh:
        spec = json.load(fh)
    methods = spec["methods"]
    out = []
    w = out.append
    w("#include-once")
    w("; SPDX-License-Identifier: GPL-3.0-or-later")
    w("; ===========================================================================================================================")
    w("; CCTelegramUDF - all Telegram Bot API methods")
    w(f"; Generated by tools/gen_methods.py from Telegram Bot API {spec['version']} ({spec['release_date']}).")
    w("; DO NOT EDIT - regenerate instead. Include CCTelegramUDF.au3, not this file.")
    w(";")
    w("; Every function returns the \"result\" of the method (see CCTelegramUDF.au3 header) or Null with @error set.")
    w("; Optional parameters go into the last argument $vOpt as Dictionary (_CCTelegram_Obj) or as JSON object string.")
    w("; Object/array parameters (reply_markup, entities, ...) accept a Dictionary/array or a JSON string.")
    w("; File parameters accept a local path (uploaded), an HTTP URL or a file_id.")
    w("; ===========================================================================================================================")
    w("")
    w(f'Global Const $CCTELEGRAM_API_VERSION = "{spec["version"].replace("Bot API ", "")}"')
    w(f'Global Const $CCTELEGRAM_API_DATE = "{spec["release_date"]}"')
    w(f"Global Const $CCTELEGRAM_API_METHODS = {len(methods)}")
    w("")

    meta = []
    seen = set()
    for name in sorted(methods):
        m = methods[name]
        func_suffix = name[:1].upper() + name[1:]
        if func_suffix in RESERVED_HELPERS:
            raise SystemExit(f"name collision with a helper: {name}")
        if func_suffix.lower() in seen:
            raise SystemExit(f"duplicate function name: {name}")
        seen.add(func_suffix.lower())

        fields = m.get("fields", [])
        by_name = {f["name"]: f for f in fields}
        # positional: chat_id, message_id (only together with chat_id) and all required fields,
        # always in the order of the documentation
        wanted = {f["name"] for f in fields if f["required"]}
        if "chat_id" in by_name:
            wanted.add("chat_id")
            if "message_id" in by_name:
                wanted.add("message_id")
        positional = [f for f in fields if f["name"] in wanted]
        optional = [f for f in fields if f["name"] not in wanted]

        json_fields = [f["name"] for f in fields if kind(f["types"]) == "json"]
        file_fields = [f["name"] for f in fields if kind(f["types"]) == "file"]
        jf = "|" + "|".join(json_fields) + "|" if json_fields else ""
        ff = "|" + "|".join(file_fields) + "|" if file_fields else ""
        meta.append((name, jf, ff))

        args = []
        for f in positional:
            args.append("$" + prefix(f["types"]) + camel(f["name"]))
        sig = ", ".join(args + (["$vOpt = Default"] if optional else []))

        # header
        w("; #FUNCTION# ================================================================================================================")
        w(f"; Name ..........: _CCTelegram_{func_suffix}")
        w(f"; API method ....: {name}   {m['href']}")
        w(f"; Returns .......: {type_text(m.get('returns', ['?']))}")
        if positional:
            first = True
            width = max(len("$" + prefix(f["types"]) + camel(f["name"])) for f in positional)
            for f in positional:
                var = "$" + prefix(f["types"]) + camel(f["name"])
                req = "" if f["required"] else " - may be Default"
                label = "; Parameters ....: " if first else ";                  "
                w(f"{label}{var.ljust(width)} - {f['name']} ({type_text(f['types'])}){req}")
                first = False
        if optional:
            label = "; Parameters ....: " if not positional else ";                  "
            w(f"{label}$vOpt - [optional] Dictionary/JSON with:")
            text = ", ".join(f"{f['name']} ({type_text(f['types'])})" for f in optional)
            for line in textwrap.wrap(text, 96):
                w(";                          " + line)
        if not positional and not optional:
            w("; Parameters ....: none")
        w("; ===========================================================================================================================")
        w(f"Func _CCTelegram_{func_suffix}({sig})")
        if optional:
            w("    Local $oP = __CCTelegram_Params($vOpt)")
            w("    If @error Then Return SetError($CCTELEGRAM_ERR_INPUT, 0, Null)")
        else:
            w('    Local $oP = ObjCreate("Scripting.Dictionary")')
        for f, a in zip(positional, args):
            w(f'    __CCTelegram_Set($oP, "{f["name"]}", {a})')
        w(f'    Local $vRes = __CCTelegram_Request("{name}", $oP, "{jf}", "{ff}")')
        w("    Return SetError(@error, @extended, $vRes)")
        w(f"EndFunc   ;==>_CCTelegram_{func_suffix}")
        w("")

    # metadata for _CCTelegram_Call
    w("; Internal: parameter metadata for _CCTelegram_Call (object/array parameters and file parameters per method)")
    w("Func __CCTelegram_Meta($sMethod, ByRef $sJsonFields, ByRef $sFileFields)")
    w('    $sJsonFields = ""')
    w('    $sFileFields = ""')
    w("    Switch $sMethod")
    for name, jf, ff in meta:
        if not jf and not ff:
            continue
        w(f'        Case "{name}"')
        if jf:
            w(f'            $sJsonFields = "{jf}"')
        if ff:
            w(f'            $sFileFields = "{ff}"')
    w("        Case Else")
    w("            Return False")
    w("    EndSwitch")
    w("    Return True")
    w("EndFunc   ;==>__CCTelegram_Meta")
    w("")

    with open(out_path, "w", encoding="utf-8-sig", newline="\r\n") as fh:
        fh.write("\n".join(out))
    print(f"{len(methods)} methods written to {out_path} ({spec['version']}, {spec['release_date']})")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_methods.py <api.json> <CCTelegramUDF_Methods.au3>")
    main(sys.argv[1], sys.argv[2])
